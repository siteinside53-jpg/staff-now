import { readdirSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Οι εικόνες του φόντου της αρχικής.
 *
 * ΠΩΣ ΜΠΑΙΝΟΥΝ: ρίχνεις αρχεία στο `apps/web/public/hero/` και ξαναχτίζεις.
 * Τίποτα άλλο. Αν ο φάκελος είναι άδειος, το φόντο μένει με τα σχέδια —
 * δεν σπάει ποτέ τίποτα.
 *
 * ΤΙ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΜΠΕΙ (διάβασέ το πριν ανεβάσεις):
 *
 * ✅ Πρόσωπα φτιαγμένα με AI — δεν είναι υπαρκτοί άνθρωποι, κανείς δεν μπορεί
 *    να πει «χρησιμοποιείς τη φάτσα μου».
 * ✅ Χώροι χωρίς ταυτότητα: εσωτερικό ταβέρνας, ρεσεψιόν ξενοδοχείου, μπαρ σε
 *    παραλία, ταμείο μίνι μάρκετ, κουζίνα. Γενικά, όχι συγκεκριμένα.
 *
 * ❌ Λογότυπα ή καταστήματα αναγνωρίσιμων αλυσίδων (σούπερ μάρκετ, ξενοδοχεία,
 *    καφετέριες). Διαβάζεται σαν «αυτοί είναι πελάτες μας» ενώ δεν είναι, και
 *    τα σήματά τους προστατεύονται.
 * ❌ Φωτογραφίες πραγματικών χρηστών της πλατφόρμας. Ανέβασαν φωτογραφία για
 *    να τη δει επιχείρηση που τους ενδιαφέρεται, όχι για διαφήμιση.
 * ❌ Όνομα ή «μαρτυρία» κολλημένη πάνω σε AI πρόσωπο («Μαρία, σερβιτόρα:
 *    βρήκα δουλειά σε 2 μέρες»). Αυτό είναι ψεύτικη κριτική και απαγορεύεται.
 *
 * Καθαρά διακοσμητικές είναι — γι' αυτό μπαίνουν πολύ αχνές, χωρίς λεζάντα.
 */

const ALLOWED = ['.jpg', '.jpeg', '.png', '.webp', '.avif'];

export function heroPhotos(): string[] {
  try {
    return readdirSync(join(process.cwd(), 'public', 'hero'))
      .filter((f) => ALLOWED.some((ext) => f.toLowerCase().endsWith(ext)))
      .sort()
      .map((f) => `/hero/${f}`);
  } catch {
    // Ο φάκελος δεν υπάρχει ακόμη — μια χαρά, γυρνάμε στα σχέδια.
    return [];
  }
}
