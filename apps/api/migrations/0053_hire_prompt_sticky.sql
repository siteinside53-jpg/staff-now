-- Η ερώτηση «έγινε πρόσληψη;» μένει ανοιχτή μέχρι να απαντηθεί.
--
-- Πριν, η ερώτηση υπολογιζόταν κάθε φορά από την ώρα του τελευταίου μηνύματος:
-- εμφανιζόταν μετά από 2 μέρες σιωπής και ΕΞΑΦΑΝΙΖΟΤΑΝ μόλις γραφόταν
-- οτιδήποτε. Ένα «ναι, τα λέμε» αρκούσε για να χαθεί, και συχνά δεν ξαναρχόταν
-- ποτέ. Τώρα κρατάμε πότε άνοιξε· από κει και πέρα φεύγει μόνο όταν δηλωθεί
-- πρόσληψη ή πατηθεί «Όχι ακόμη».
--
-- ΠΡΟΣΟΧΗ: η SQLite δεν έχει ADD COLUMN IF NOT EXISTS, οπότε σε επανεκτέλεση το
-- ALTER αποτυγχάνει με "duplicate column name". Γι' αυτό αυτό το αρχείο μπαίνει
-- ΤΕΛΕΥΤΑΙΟ — ίδια λογική με τα 0041/0047/0051.

ALTER TABLE hire_prompts ADD COLUMN first_shown_at TEXT;

-- Το ερώτημα των προτροπών κοιτάζει πρώτα αυτή τη στήλη.
CREATE INDEX IF NOT EXISTS idx_hire_prompts_first_shown
  ON hire_prompts(first_shown_at);
