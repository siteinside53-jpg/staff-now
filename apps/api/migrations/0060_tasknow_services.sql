-- «Προσφέρω υπηρεσία» — η άλλη πλευρά των μικροδουλειών.
--
-- Μέχρι τώρα υπήρχε μόνο η μία κατεύθυνση: κάποιος ΖΗΤΑΕΙ βοήθεια και περιμένει
-- προσφορές. Αυτό σημαίνει ότι οι 105 εγγεγραμμένοι εργαζόμενοι δεν έχουν
-- τίποτα να κάνουν μέχρι να ανεβάσει κάποιος δουλειά — κάθονται και περιμένουν.
-- Εδώ μπορούν να πουν «κάνω καθαρισμούς, 15€/ώρα, στην Καλαμαριά» και να τους
-- βρίσκουν.
--
-- ── ΓΙΑΤΙ ΜΟΝΟ ΑΥΤΕΣ ΜΠΑΙΝΟΥΝ ΣΤΟΝ ΧΑΡΤΗ ────────────────────────────────────
--
-- Απόφαση του ιδιοκτήτη, και είναι σωστή: η τοποθεσία κάποιου που ΖΗΤΑΕΙ
-- βοήθεια είναι το σπίτι του. Δημόσιος χάρτης με πινέζες σε σπίτια ανθρώπων που
-- περιμένουν άγνωστο να χτυπήσει την πόρτα είναι κακή ιδέα, όσο θολή κι αν
-- είναι η πινέζα.
--
-- Ο πάροχος υπηρεσίας είναι άλλη περίπτωση: διαφημίζεται ο ίδιος, με τη θέλησή
-- του, και αυτό που δηλώνει ΔΕΝ είναι η διεύθυνσή του αλλά Η ΠΕΡΙΟΧΗ ΠΟΥ
-- ΕΞΥΠΗΡΕΤΕΙ. Γι' αυτό κρατάμε σημείο ΚΑΙ ακτίνα: ο χάρτης δείχνει κύκλο
-- κάλυψης, όχι πόρτα. Ένας υδραυλικός που καλύπτει «Καλαμαριά, 3 χλμ γύρω» δεν
-- αποκαλύπτει πού μένει.
--
-- Γραμμένο μόνο με CREATE ... IF NOT EXISTS: το db:migrate ξανατρέχει ΟΛΑ τα
-- αρχεία και το SQLite δεν έχει «ADD COLUMN IF NOT EXISTS».

CREATE TABLE IF NOT EXISTS tasknow_services (
  id          TEXT PRIMARY KEY,
  user_id     TEXT NOT NULL,

  -- «Καθαρισμοί σπιτιών», «Μεταφορές με κλούβα», «Ιδιαίτερα μαθηματικών»
  title       TEXT NOT NULL,
  description TEXT,
  category    TEXT NOT NULL,

  -- Η τιμή και η μονάδα της: 15 + «/ώρα», 40 + «/δουλειά», 0 + «κατόπιν συνεννόησης»
  price       INTEGER,
  price_unit  TEXT,

  -- Η ΠΕΡΙΟΧΗ ΠΟΥ ΕΞΥΠΗΡΕΤΕΙ. Κέντρο κύκλου, όχι διεύθυνση.
  area        TEXT NOT NULL,
  lat         REAL,
  lon         REAL,
  -- Πόσο μακριά πηγαίνει. Η ακτίνα είναι που κάνει τον χάρτη να δείχνει
  -- κάλυψη αντί για σημείο — και είναι η ίδια η προστασία.
  radius_km   REAL NOT NULL DEFAULT 3,

  -- active | paused
  status      TEXT NOT NULL DEFAULT 'active',
  -- Απόκρυψη από το διαχειριστικό.
  hidden      INTEGER NOT NULL DEFAULT 0,
  flag_reason TEXT,

  created_at  TEXT NOT NULL,
  updated_at  TEXT NOT NULL
);

-- Το ερώτημα του χάρτη: ό,τι είναι ενεργό, νεότερα πρώτα.
CREATE INDEX IF NOT EXISTS idx_tasknow_services_public
  ON tasknow_services(status, hidden, created_at);

-- «Οι υπηρεσίες μου»
CREATE INDEX IF NOT EXISTS idx_tasknow_services_user
  ON tasknow_services(user_id, created_at);
