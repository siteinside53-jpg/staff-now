-- Πού ακριβώς είναι η μικροδουλειά.
--
-- Μέχρι τώρα κρατούσαμε μόνο το όνομα της γειτονιάς, από λίστα με 11 επιλογές.
-- Άρα ΟΛΕΣ οι δουλειές της Καλαμαριάς κάθονταν στο ίδιο ακριβώς σημείο του
-- χάρτη — που σημαίνει ότι ο χάρτης δεν έλεγε τίποτα χρήσιμο.
--
-- ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟΣ ΠΙΝΑΚΑΣ ΚΑΙ ΟΧΙ ΔΥΟ ΝΕΕΣ ΣΤΗΛΕΣ: το db:migrate ξανατρέχει
-- ΟΛΑ τα αρχεία κάθε φορά, και το SQLite δεν έχει «ADD COLUMN IF NOT EXISTS».
-- Μια νέα στήλη θα έσκαγε στο δεύτερο τρέξιμο και θα κοκκίνιζε το ανέβασμα.
-- Με CREATE TABLE IF NOT EXISTS δεν υπάρχει τέτοιο θέμα.
--
-- ΤΟ ΣΗΜΕΙΟ ΕΔΩ ΕΙΝΑΙ ΤΟ ΑΚΡΙΒΕΣ.
--
-- Δημόσια ΔΕΝ φεύγει ποτέ αυτούσιο: ο server το μετατοπίζει λίγο πριν το
-- στείλει, ώστε στον χάρτη να φαίνεται περιοχή και όχι πόρτα σπιτιού. Δεν
-- αρκεί να ζωγραφίσουμε κύκλο στην οθόνη — όποιος κοιτάξει τι κατεβάζει ο
-- browser θα έβλεπε τη σωστή διεύθυνση. Η μετατόπιση γίνεται στον server.
--
-- Το ακριβές σημείο το βλέπουν μόνο δύο άνθρωποι: αυτός που ανέβασε τη
-- δουλειά, και αυτός που τελικά επιλέχθηκε για να την κάνει.

CREATE TABLE IF NOT EXISTS tasknow_task_points (
  task_id TEXT PRIMARY KEY,
  lat     REAL NOT NULL,
  lon     REAL NOT NULL
);


