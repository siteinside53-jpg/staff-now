-- Ακύρωση συνεδριών (tokens) με μία στήλη.
--
-- Το πρόβλημα: το token ζει 72 ώρες και τίποτα δεν το σκότωνε. Η αποσύνδεση
-- έσβηνε μόνο το cookie του browser, και η αλλαγή κωδικού δεν το άγγιζε καθόλου.
-- Δηλαδή αν κάποιος σου έκλεβε το token, δεν υπήρχε τρόπος να τον διώξεις.
--
-- Η λύση: κρατάμε ανά χρήστη μια χρονική στιγμή. Κάθε token που εκδόθηκε ΠΡΙΝ
-- από αυτήν θεωρείται άκυρο. Στην αποσύνδεση και στην αλλαγή/επαναφορά κωδικού
-- τη σπρώχνουμε στο «τώρα» και όλα τα παλιά tokens πεθαίνουν ακαριαία.
--
-- Γιατί στήλη και όχι ξεχωριστός πίνακας: το requireAuth κάνει ήδη ένα SELECT
-- στον users σε κάθε αίτημα. Προσθέτοντας τη στήλη εκεί, ο έλεγχος δεν κοστίζει
-- ούτε ένα επιπλέον ερώτημα.
--
-- NULL = δεν έχει γίνει ποτέ ακύρωση, όλα τα tokens ισχύουν. Έτσι κανένας από
-- τους ήδη συνδεδεμένους χρήστες δεν πετάγεται έξω όταν ανέβει η αλλαγή.
ALTER TABLE users ADD COLUMN sessions_valid_from TEXT;
