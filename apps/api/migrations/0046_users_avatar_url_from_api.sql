-- Συνέχεια του 0042_serve_files_from_api.sql.
--
-- Εκείνο μετέφερε οκτώ στήλες από το `pub-<hash>.r2.dev` στον server του API,
-- αλλά ΞΕΧΑΣΕ τη `users.avatar_url` — τη «Φωτογραφία Λογαριασμού» που
-- εμφανίζεται στις Ρυθμίσεις, κάτω αριστερά στο πλαϊνό μενού και στα μηνύματα.
-- Γι' αυτό ο λογαριασμός έδειχνε σπασμένη εικόνα ενώ το αρχείο υπήρχε κανονικά.
--
-- Έλεγχος στην παραγωγή πριν την εκτέλεση:
--   users με avatar .................. 4
--   από αυτούς σε r2.dev (σπασμένα) .. 4
--   ήδη σωστά (/uploads/f/) .......... 0
-- Και τα 4 αρχεία επιβεβαιώθηκε ότι σερβίρονται κανονικά από το API
-- (HTTP 200, image/jpeg & image/png), οπότε αλλάζει μόνο το κομμάτι του URL
-- πριν από το κλειδί — το ίδιο το αρχείο μένει ως έχει.
--
-- Καμία άλλη στήλη δεν έχει μείνει πίσω: έγινε σάρωση όλου του σχήματος για
-- στήλες url/photo/logo/avatar/content/document και όλες βγήκαν 0.
--
-- Επαναλήψιμο: το REPLACE δεν βρίσκει τίποτα σε δεύτερη εκτέλεση.

UPDATE users
SET avatar_url = REPLACE(avatar_url,
      'https://pub-5e055b34e4694e02ac3de198a7776878.r2.dev/',
      'https://staffnow-api-production.siteinside53.workers.dev/uploads/f/')
WHERE avatar_url LIKE '%pub-5e055b34e4694e02ac3de198a7776878.r2.dev/%';
