-- Απόρριψη αιτήματος ενδιαφέροντος.
--
-- ΤΙ ΕΛΕΙΠΕ: στη σελίδα «Ποιος Ενδιαφέρθηκε» υπήρχαν μόνο δύο κουμπιά — «δες
-- προφίλ» και «✓ ενδιαφέρομαι». Δεν υπήρχε τρόπος να πεις «όχι, ευχαριστώ».
-- Οπότε κάθε αίτημα που δεν σε ενδιέφερε έμενε στη λίστα για πάντα, και η
-- λίστα γέμιζε με πράγματα που ο χρήστης είχε ήδη προσπεράσει νοητικά. Τα
-- αιτήματα του Ιουλίου που «ξέμειναν» είναι ακριβώς αυτό.
--
-- ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟΣ ΠΙΝΑΚΑΣ ΚΑΙ ΟΧΙ ΝΕΑ ΣΤΗΛΗ ΣΤΑ swipes:
--
--   1. Το db:migrate ξανατρέχει ΟΛΑ τα αρχεία κάθε φορά. Το SQLite δεν έχει
--      «ADD COLUMN IF NOT EXISTS», άρα μια νέα στήλη θα έσκαγε στο δεύτερο
--      τρέξιμο. Με CREATE TABLE IF NOT EXISTS δεν υπάρχει τέτοιο θέμα.
--   2. Η απόρριψη είναι πράξη του ΠΑΡΑΛΗΠΤΗ, ενώ η γραμμή στα swipes ανήκει
--      σε αυτόν που έστειλε το ενδιαφέρον. Δεν πειράζουμε ξένη εγγραφή.
--   3. Έτσι η απόρριψη αναιρείται καθαρά: σβήνεις τη γραμμή και το αίτημα
--      επιστρέφει στη λίστα ακριβώς όπως ήταν. Τίποτα δεν χάνεται.

CREATE TABLE IF NOT EXISTS interest_dismissals (
  id         TEXT PRIMARY KEY,
  -- Ποιος απέρριψε (ο παραλήπτης του ενδιαφέροντος).
  user_id    TEXT NOT NULL,
  -- Ποιο αίτημα απέρριψε.
  swipe_id   TEXT NOT NULL,
  created_at TEXT NOT NULL,
  UNIQUE (user_id, swipe_id)
);

-- Το ερώτημα που τρέχει σε κάθε φόρτωση της σελίδας: «ποια έχω απορρίψει;»
CREATE INDEX IF NOT EXISTS idx_interest_dismissals_user
  ON interest_dismissals(user_id);
