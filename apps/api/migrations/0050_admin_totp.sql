-- Διπλή επαλήθευση (2FA) με 6ψήφιο κωδικό από εφαρμογή κινητού.
--
-- Το πρόβλημα: ο λογαριασμός admin προστατεύεται ΜΟΝΟ από έναν κωδικό. Όποιος
-- τον μάθει —από διαρροή άλλης ιστοσελίδας, από ψεύτικο email, από ιό— μπαίνει
-- και βλέπει κάθε χρήστη, κάθε μήνυμα, κάθε πληρωμή. Η ασφάλεια όλης της
-- πλατφόρμας είναι όση και η ασφάλεια αυτού του ενός κωδικού.
--
-- Η λύση: δεύτερο εμπόδιο που ΔΕΝ ταξιδεύει με τον κωδικό. Ένας 6ψήφιος που
-- παράγεται μέσα στο κινητό και αλλάζει κάθε 30 δευτερόλεπτα (πρότυπο RFC 6238).
-- Δεν στέλνεται SMS ούτε email, άρα δεν κοστίζει τίποτα και δουλεύει χωρίς σήμα.
--
-- Όλες οι στήλες είναι NULL εξ ορισμού, άρα:
--   * καμία υπάρχουσα γραμμή δεν αλλάζει,
--   * κανένας χρήστης δεν πετάγεται έξω όταν ανέβει η αλλαγή,
--   * η διπλή επαλήθευση ανεβαίνει ΣΒΗΣΤΗ και ανάβει χειροκίνητα, ανά λογαριασμό.
--
-- ════════════════════════════════════════════════════════════════════════════
--  ΕΝΤΟΛΗ ΕΚΤΑΚΤΗΣ ΑΝΑΓΚΗΣ — «έχασα το κινητό μου, κλειδώθηκα έξω»
-- ════════════════════════════════════════════════════════════════════════════
--  Πρώτα δοκίμασε: (1) έναν από τους 10 κωδικούς ανάκτησης, (2) το κουμπί
--  «Απενεργοποίηση» στις Ρυθμίσεις. Αν τίποτα δεν δουλεύει, από τον υπολογιστή
--  σου, μέσα στον φάκελο του έργου:
--
--    npx wrangler d1 execute staffnow-db-prod --remote -c apps/api/wrangler.toml \
--      --env production --command \
--      "UPDATE users SET totp_secret=NULL, totp_enabled_at=NULL, \
--       totp_pending_secret=NULL, totp_pending_expires_at=NULL, \
--       totp_recovery_codes=NULL, totp_last_step=NULL WHERE email='ΤΟ_EMAIL_ΣΟΥ'"
--
--  Αν έχει κλειδώσει και το φρένο των προσπαθειών:
--
--    npx wrangler kv key delete --namespace-id 817d9666ea2e46288a31b02d6a914a10 \
--      "2fa_fails:ΤΟ_ID_ΤΟΥ_ΧΡΗΣΤΗ"
--
--  Μετά από οποιαδήποτε από τις δύο, μπαίνεις με σκέτο email + κωδικό.
-- ════════════════════════════════════════════════════════════════════════════

-- Το ενεργό μυστικό, σε μορφή base32 (αυτό που γράφεις στην εφαρμογή).
ALTER TABLE users ADD COLUMN totp_secret TEXT;

-- Πότε ενεργοποιήθηκε. Το `if` της σύνδεσης απαιτεί ΚΑΙ τα δύο να υπάρχουν,
-- ώστε ένα μισοτελειωμένο στήσιμο να μην μπορεί ποτέ να μπλοκάρει τη σύνδεση.
ALTER TABLE users ADD COLUMN totp_enabled_at TEXT;

-- Μυστικό ΥΠΟ ΔΟΚΙΜΗ. Ζει εδώ όσο ο χρήστης στήνει την εφαρμογή και γίνεται
-- ενεργό μόνο αφού στείλει έναν σωστό ζωντανό κωδικό. Έτσι, αν πληκτρολογήσει
-- λάθος το κλειδί, η ενεργοποίηση απλώς δεν ολοκληρώνεται — δεν κλειδώνεται έξω.
ALTER TABLE users ADD COLUMN totp_pending_secret TEXT;
ALTER TABLE users ADD COLUMN totp_pending_expires_at TEXT;

-- Οι 10 κωδικοί ανάκτησης, ως JSON πίνακας από hashes (PBKDF2, ίδιος μηχανισμός
-- με τους κωδικούς πρόσβασης). Ποτέ σε καθαρό κείμενο: όποιος διαβάσει τη βάση
-- δεν βρίσκει τίποτα χρησιμοποιήσιμο. Κάθε χρήση αφαιρεί ένα στοιχείο.
ALTER TABLE users ADD COLUMN totp_recovery_codes TEXT;

-- Το τελευταίο «βήμα 30 δευτερολέπτων» που έγινε δεκτό. Οτιδήποτε <= αυτού
-- απορρίπτεται, ώστε ένας 6ψήφιος που τον είδε κάποιος πάνω από τον ώμο σου να
-- μην ξαναδουλεύει μέσα στα 30 δευτερόλεπτά του.
ALTER TABLE users ADD COLUMN totp_last_step TEXT;
